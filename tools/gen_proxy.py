"""Generate the powrprof.dll proxy sources from the real DLL's export table.

Usage: python -I tools/gen_proxy.py [C:/Windows/System32/powrprof.dll]

Writes src/powrprof.def, src/powrprof_stubs.asm and src/powrprof_names.inc. Every export of
the real library gets a stub that jumps through a pointer the DLL fills at load time, so
anything in the process that imports powrprof keeps working, not only the server's two
functions.
"""
import pathlib
import site
import sys

sys.path.insert(0, site.getusersitepackages())
import pefile  # noqa: E402

src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else r"C:\Windows\System32\powrprof.dll")
out = pathlib.Path(__file__).resolve().parent.parent / "src"

pe = pefile.PE(str(src))
exports = sorted(
    ((s.ordinal, s.name.decode()) for s in pe.DIRECTORY_ENTRY_EXPORT.symbols if s.name),
    key=lambda e: e[0],
)

(out / "powrprof.def").write_text(
    "LIBRARY powrprof\nEXPORTS\n"
    + "".join(f"    {name}=xs_{name} @{ordinal}\n" for ordinal, name in exports),
    encoding="ascii",
)

asm = ["; Generated by tools/gen_proxy.py. Each stub jumps to the real powrprof export.",
       "EXTERN g_powrprof_real:QWORD", ".code"]
for index, (_, name) in enumerate(exports):
    asm += [f"xs_{name} PROC", f"    jmp qword ptr [g_powrprof_real + {index * 8}]", f"xs_{name} ENDP"]
asm.append("END")
(out / "powrprof_stubs.asm").write_text("\n".join(asm) + "\n", encoding="ascii")

(out / "powrprof_names.inc").write_text(
    "// Generated by tools/gen_proxy.py, in stub order.\n"
    + "".join(f'"{name}",\n' for _, name in exports),
    encoding="ascii",
)
print(f"{len(exports)} exports from {src}")
